import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { lstat, readdir, writeFile } from "node:fs/promises";
import { basename, join, relative } from "node:path";
import { sha256File } from "./archives.ts";

/**
 * Builds the NSIS installer from a packaged Windows app directory with plain
 * `makensis`, which runs on Linux without Wine. The uninstaller removes
 * exactly the files listed here and nothing else.
 */

export interface PayloadEntry {
  /** Path relative to the app directory, with "/" separators. */
  path: string;
  directory: boolean;
  size: number;
}

export async function listPayload(root: string): Promise<PayloadEntry[]> {
  const entries: PayloadEntry[] = [];
  async function walk(directory: string): Promise<void> {
    for (const name of (await readdir(directory)).sort()) {
      const full = join(directory, name);
      const info = await lstat(full);
      const path = relative(root, full).split("\\").join("/");
      if (info.isSymbolicLink())
        throw new Error(`The app directory contains a link: ${path}`);
      if (info.isDirectory()) {
        entries.push({ path, directory: true, size: 0 });
        await walk(full);
      } else if (info.isFile()) {
        entries.push({ path, directory: false, size: info.size });
      } else throw new Error(`Unsupported entry in the app directory: ${path}`);
    }
  }
  await walk(root);
  return entries;
}

/** A path safe to place inside a double-quoted NSIS string. */
export function nsisPath(path: string): string {
  if (/["\u0000-\u001f]/u.test(path))
    throw new Error("A payload path cannot be represented safely in NSIS");
  return path.split("/").join("\\").replaceAll("$", "$$$$");
}

/** The uninstall steps: every file, then directories deepest first. */
export function uninstallList(entries: readonly PayloadEntry[]): string {
  const lines = ["; Generated by scripts/windows/installer.ts. Do not edit."];
  for (const entry of entries)
    if (!entry.directory)
      lines.push(`Delete "$INSTDIR\\${nsisPath(entry.path)}"`);
  const directories = entries
    .filter((entry) => entry.directory)
    .sort(
      (a, b) =>
        b.path.split("/").length - a.path.split("/").length ||
        a.path.localeCompare(b.path),
    );
  for (const entry of directories)
    lines.push(`RMDir "$INSTDIR\\${nsisPath(entry.path)}"`);
  return `${lines.join("\r\n")}\r\n`;
}

/** "0.0.1" becomes "0.0.1.0" for the Windows version resource. */
export function versionQuad(version: string): string {
  const match = /^(\d{1,4})\.(\d{1,4})\.(\d{1,4})(?:[-+].*)?$/u.exec(version);
  assert.ok(match, `Unsupported version: ${version}`);
  return `${match[1]}.${match[2]}.${match[3]}.0`;
}

export interface InstallerOptions {
  /** Packaged app directory (contains ai-video-editor.exe). */
  appDirectory: string;
  outputDirectory: string;
  productName: string;
  version: string;
  licenseFile: string;
  /** A .ico for the installer and uninstaller windows. */
  iconFile?: string;
  /** Path to makensis, or "makensis" from PATH. */
  makensis: string;
  /** Directory holding NSIS's Stubs/Include/Contrib when relocated. */
  nsisDirectory?: string | undefined;
  /** Fast zlib compression for smoke tests; release builds use LZMA. */
  fast?: boolean | undefined;
  /** Command that signs a file; omit while no certificate exists. */
  signCommand?: string | undefined;
}

export interface InstallerResult {
  installer: string;
  size: number;
  sha256: string;
  fileCount: number;
  payloadBytes: number;
  makensisVersion: string;
  signed: false | "signing-command-ran";
  compression: "lzma-solid" | "zlib";
}

export async function buildInstaller(
  options: InstallerOptions,
): Promise<InstallerResult> {
  const exe = join(options.appDirectory, "ai-video-editor.exe");
  assert.ok((await lstat(exe)).isFile(), "ai-video-editor.exe is missing");
  const entries = await listPayload(options.appDirectory);
  const list = join(options.outputDirectory, "uninstall-files.nsh");
  await writeFile(list, uninstallList(entries));
  const installer = join(
    options.outputDirectory,
    `ai-video-editor-${options.version}-win32-x64-setup${options.fast ? "-fast" : ""}.exe`,
  );
  const env = {
    ...process.env,
    ...(options.nsisDirectory ? { NSISDIR: options.nsisDirectory } : {}),
  };
  const makensisVersion = execFileSync(options.makensis, ["-VERSION"], {
    env,
    encoding: "utf8",
  }).trim();
  const args = [
    "-V2",
    "-INPUTCHARSET",
    "UTF8",
    `-DPRODUCT_NAME=${options.productName}`,
    `-DPRODUCT_VERSION=${options.version}`,
    `-DPRODUCT_VERSION_QUAD=${versionQuad(options.version)}`,
    `-DSOURCE_DIR=${options.appDirectory}`,
    `-DOUT_FILE=${installer}`,
    `-DUNINSTALL_LIST=${list}`,
    `-DLICENSE_FILE=${options.licenseFile}`,
    ...(options.iconFile ? [`-DICON_FILE=${options.iconFile}`] : []),
    ...(options.fast ? ["-DFAST"] : []),
    ...(options.signCommand ? [`-DSIGN_COMMAND=${options.signCommand}`] : []),
    join(import.meta.dirname, "installer.nsi"),
  ];
  execFileSync(options.makensis, args, { env, stdio: "inherit" });
  const info = await lstat(installer);
  assert.ok(info.isFile() && info.size > 0, `${basename(installer)} not built`);
  const sha256 = await sha256File(installer);
  await writeFile(`${installer}.sha256`, `${sha256}  ${basename(installer)}\n`);
  return {
    installer,
    size: info.size,
    sha256,
    fileCount: entries.filter((entry) => !entry.directory).length,
    payloadBytes: entries.reduce((sum, entry) => sum + entry.size, 0),
    makensisVersion,
    signed: options.signCommand ? "signing-command-ran" : false,
    compression: options.fast ? "zlib" : "lzma-solid",
  };
}
